#!/usr/bin/env python3
"""Robustness table (B5 controls, B6 contiguous ranges, B7 second model): observed SharedScan gains against the frozen
primary-model predictions, plus the comparison with adaptive batching where it was run.

Gains follow the preregistered scoring (confirm_score.py): the best modeled baseline (P1_eager, P2_window30; whichever
the cell has) by mean makespan over the cell's seeds, divided by the mean SharedScan makespan. A cell enters the table
only if every frozen seed has exactly the frozen policy list, each run for every seed and with all queries completed.
Writes paper/sections/robust_table.tex and figures/robust_data.json."""
import argparse
import json
import os

import numpy as np

from table_style import ratio

BLOCKS = [("b5", "b5_freeze.json"), ("b6", "b6_freeze.json"), ("b7", "b7_freeze.json")]
LABEL = {
    "pubmed_k1600_l3_noapc": "PubMed, no APC",
    "pubmed_k1600_l3_inflight": "PubMed, in flight",
    "pubmed_k1600_l3_low": "PubMed, 5--20\\% ranges",
    "arxiv_k1600_l3_low": "arXiv, 5--20\\% ranges",
    "pubmed_k1600_l3_nowrap": "PubMed, contiguous",
    "arxiv_k1600_l3_nowrap": "arXiv, contiguous",
    "pubmed_k1600_l3_q4b": "PubMed, Qwen3-4B",
    "arxiv_k1600_l3_q4b": "arXiv, Qwen3-4B",
}
MODELED = ("P1_eager", "P2_window30")


def load_cell(d, name, cell):
    runs = {}
    for s in cell["seeds"]:
        try:
            R = json.load(open(os.path.join(d, f"{name}_s{s}.json")))
        except (OSError, ValueError):
            return None
        if [r["policy"] for r in R["runs"]] != cell["policies"]:
            return None
        if any(r.get("seed") != s or r.get("completed") != cell["m"] for r in R["runs"]):
            return None
        runs[s] = {r["policy"]: r for r in R["runs"]}
    return runs


def mean(runs, pol, key):
    return float(np.mean([runs[s][pol][key] for s in runs]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, help="project results root containing results/b5, b6, b7")
    ap.add_argument("--tex", required=True)
    ap.add_argument("--json", required=True)
    a = ap.parse_args()
    rows, missing = [], []
    for blk, fname in BLOCKS:
        d = os.path.join(a.root, "results", blk)
        try:
            F = json.load(open(os.path.join(d, fname)))
        except (OSError, ValueError):
            missing.append(f"{blk} (no freeze file)")
            continue
        P = F["predictions"][F["primary_model"]]["per_cell"]
        for name, cell in F["cells"].items():
            runs = load_cell(d, name, cell)
            if runs is None:
                missing.append(name)
                continue
            base = [b for b in MODELED if b in cell["policies"]]
            bm = min(base, key=lambda b: mean(runs, b, "makespan"))
            for v in [p for p in cell["policies"] if p.startswith("P6")]:
                obs = mean(runs, bm, "makespan") / mean(runs, v, "makespan")
                pbm = min(base, key=lambda b: P[name][b]["makespan"])
                pred = P[name][pbm]["makespan"] / P[name][v]["makespan"]
                row = dict(block=blk, cell=name, variant=v, best_baseline=bm, seeds=sorted(runs), gain=obs, pred_gain=pred,
                           cached=float(np.mean([runs[s][v]["cached_tokens"] / runs[s][v]["prompt_tokens"] for s in runs])),
                           pred_cached=P[name][v]["cached_frac"],
                           p95_gain_vs_best=mean(runs, bm, "p95") / mean(runs, v, "p95"),
                           gain_per_trace=[runs[s][bm]["makespan"] / runs[s][v]["makespan"] for s in runs])
                if "P2_adaptive" in cell["policies"]:
                    row["mk_vs_adaptive"] = mean(runs, "P2_adaptive", "makespan") / mean(runs, v, "makespan")
                    row["p95_vs_adaptive"] = mean(runs, "P2_adaptive", "p95") / mean(runs, v, "p95")
                    row["mk_per_trace"] = [runs[s]["P2_adaptive"]["makespan"] / runs[s][v]["makespan"] for s in runs]
                    row["p95_per_trace"] = [runs[s]["P2_adaptive"]["p95"] / runs[s][v]["p95"] for s in runs]
                rows.append(row)
    json.dump(dict(rows=rows, missing=missing), open(a.json, "w"), indent=1)
    # One block per varied factor, in the order the text discusses them; each row is the variant within that block.
    BLOCK = [("Prefix caching off", ["pubmed_k1600_l3_noapc"]), ("Blocks in flight, PubMed, $b=32$", ["pubmed_k1600_l3_inflight"]),
             ("Ranges of 5--20\\% of the collection", ["arxiv_k1600_l3_low", "pubmed_k1600_l3_low"]),
             ("Contiguous ranges", ["arxiv_k1600_l3_nowrap", "pubmed_k1600_l3_nowrap"]),
             ("Qwen3-4B, contiguous ranges", ["arxiv_k1600_l3_q4b", "pubmed_k1600_l3_q4b"])]
    CORP = lambda c: "arXiv" if c.startswith("arxiv") else "PubMed"
    lines = ["% Generated by figures/make_robust.py; do not edit by hand.",
             "\\begin{tabular}{@{}lrrrrrr}", "\\toprule",
             " & & & \\multicolumn{2}{c}{Best baseline} & \\multicolumn{2}{c}{Adaptive} \\\\", "\\cmidrule(lr){4-5}\\cmidrule(l){6-7}",
             "Configuration & Tr. & Cached & Gain & Pred. & Mk & p95 \\\\", "\\midrule"]
    done = []
    for title, names in BLOCK:
        lines.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\")
        for name in names:
            for r in [x for x in rows if x["cell"] == name]:
                done.append(id(r))
                sfx = r["variant"].replace("P6_lazyscan", "").lstrip("_")
                if name.endswith("_inflight"):
                    lab = "$F=" + (sfx[1:] if sfx else "2") + "$"
                elif name.endswith("_noapc"):
                    lab = "PubMed, $b=32$"
                elif name.endswith("_low"):
                    lab = CORP(name) + ", $b=32$"
                else:
                    lab = CORP(name) + ", $b=" + (sfx[1:] if sfx else "32") + "$"
                mk = ratio(r["mk_vs_adaptive"], r["mk_per_trace"]) if "mk_vs_adaptive" in r else "\\textendash"
                p9 = ratio(r["p95_vs_adaptive"], r["p95_per_trace"]) if "p95_vs_adaptive" in r else "\\textendash"
                lines.append(f"\\quad {lab} & {len(r['seeds'])} & {r['cached']:.2f} & {ratio(r['gain'], r['gain_per_trace'])} & {r['pred_gain']:.2f} & {mk} & {p9} \\\\")
    assert len(done) == len(rows), "a robustness row is missing from the table blocks"
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(a.tex, "w").write("\n".join(lines) + "\n")
    print(json.dumps(dict(n=len(rows), missing=missing)))
    for r in rows:
        print(r["cell"], r["variant"], "gain %.3f pred %.3f cached %.3f" % (r["gain"], r["pred_gain"], r["cached"]),
              "adaptive %s" % (("%.3f/%.3f" % (r["mk_vs_adaptive"], r["p95_vs_adaptive"])) if "mk_vs_adaptive" in r else "-"))


if __name__ == "__main__":
    main()
