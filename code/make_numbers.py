#!/usr/bin/env python3
"""Generate paper/sections/numbers.tex (LaTeX macros) from the confirmatory score file and result files, so that
every number quoted in the paper is traceable to a result artifact. Writes numbers.json alongside."""
import argparse
import json
import os


def fmt(x, nd=2):
    return f"{x:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--score", required=True, help="results/confirm/confirm_score.json")
    ap.add_argument("--figdata", required=True, help="figures/figure_data.json")
    ap.add_argument("--out", required=True, help="numbers.tex")
    a = ap.parse_args()
    S = json.load(open(a.score))
    D = json.load(open(a.figdata))
    E = S["empirical"]
    m = {}
    for corp, tag in (("pubmed", "Pm"), ("arxiv", "Ax")):
        c = E.get(f"{corp}_k1600_l3")
        if c:
            v = c["P6_lazyscan"]
            m[f"gain{tag}MkBest"] = fmt(v["makespan_gain_vs_best"])
            m[f"gain{tag}PnBest"] = fmt(v["p95_gain_vs_best"], 1)
            m[f"gain{tag}MkEager"] = fmt(v["makespan_gain_vs_eager"], 1)
            m[f"gain{tag}PnEager"] = fmt(v["p95_gain_vs_eager"], 1)
            m[f"cached{tag}Eager"] = fmt(c["per_policy"]["P1_eager"]["cached"], 3)
            m[f"cached{tag}Shared"] = fmt(c["per_policy"]["P6_lazyscan"]["cached"], 2)
        g = E.get(f"{corp}_sgl_k1600_l3")
        if g:
            m[f"gain{tag}MkSgl"] = fmt(g["P6_vs_native_lpm"]["makespan_gain"], 1)
            m[f"gain{tag}PnSgl"] = fmt(g["P6_vs_native_lpm"]["p95_gain"], 1)
    P = S["models"][S["primary_model"]]
    m["predTOneCorrect"] = P["T1"]["correct"]
    m["predTOneLong"] = P["T1"]["long_correct"]
    m["predMaxGainErr"] = fmt(100 * max(r["gain_rel_err"] for r in P["T2"]["rows"]), 1) if P["T2"]["rows"] else "--"
    m["predMaxCachedErr"] = fmt(max(r["cached_err"] for r in P["T2"]["rows"]), 3) if P["T2"]["rows"] else "--"
    m["confirmVerdict"] = S["VERDICT"].split(":")[0]
    m["mOneCorrect"] = S["models"]["M1"]["T1"]["correct"]
    lines = ["% Generated by figures/make_numbers.py from " + os.path.basename(a.score) + "; do not edit by hand."]
    for k, v in sorted(m.items()):
        lines.append(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}")
    open(a.out, "w").write("\n".join(lines) + "\n")
    json.dump(m, open(os.path.splitext(a.out)[0] + ".json", "w"), indent=1)
    print(json.dumps(m, indent=1))


if __name__ == "__main__":
    main()
