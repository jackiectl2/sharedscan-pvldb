#!/usr/bin/env python3
"""Scope table (block B8): SharedScan against the frozen prediction and adaptive batching, from results/b8/summary.json
(idea-stage/pilots/b8_summary.py). A cell enters with the seeds that completed; the Tr. column states how many.
The gain is over the better of eager and the 30 s window, except in the F=1 cells, which have no window and use eager.
Extraction has no reportable prediction because the model has no decode cost.
Usage: make_scope.py <summary.json> <out.tex>"""
import json
import sys

ROWS = [("arxiv_k1600_l3_dist", "arXiv, distinct"), ("pubmed_k1600_l3_dist", "PubMed, distinct"),
        ("arxiv_k1600_l3_burst", "arXiv, hyperexp."), ("pubmed_k1600_l3_burst", "PubMed, hyperexp."),
        ("arxiv_k1600_l3_extract", "arXiv, extraction"),
        ("arxiv_k1600_l3_f1", "arXiv, contiguous"), ("pubmed_k1600_l3_f1", "PubMed, contiguous"),
        ("arxiv_n5000_k1600_l3", "arXiv 5k, K1.6k"), ("arxiv_n5000_k10000_l3", "arXiv 5k, K10k"),
        ("pubmed_n3000_k1600_l3", "PubMed 3k, K1.6k"), ("pubmed_n3000_k10000_l3", "PubMed 3k, K10k")]
VAR = {"P6_lazyscan": "b32 F2", "P6_lazyscan_F1": "b32 F1", "P6_lazyscan_b16": "b16 F2", "P6_lazyscan_b16_F1": "b16 F1"}


def main():
    S = json.load(open(sys.argv[1]))
    lines = ["% Generated by figures/make_scope.py; do not edit by hand.", "\\begin{tabular}{llrrrrrr}", "\\toprule",
             "Configuration & \\sys & Tr. & Gain & Pred. & Cached & Mk & p95 \\\\", "\\midrule"]
    for cell, label in ROWS:
        if cell not in S:
            continue
        r = S[cell]
        for v in [x for x in VAR if x in r["gain"]]:
            g = r["gain"][v]
            pred = f"{g['pred']:.2f}" if "pred" in g else "--"
            lines.append(f"{label} & {VAR[v]} & {len(r['seeds'])} & {g['vs_best']:.2f} & {pred} & {r['policies'][v]['cached']:.2f} & {g['vs_adaptive']:.2f} & {g['p95_vs_adaptive']:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
