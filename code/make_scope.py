#!/usr/bin/env python3
"""Scope table (block B8): SharedScan against the frozen prediction and adaptive batching, from results/b8/summary.json
(idea-stage/pilots/b8_summary.py). A cell enters with the seeds that completed; the Tr. column states how many.
The gain is over the better of eager and the 30 s window, except in the F=1 cells, which have no window and use eager.
Extraction has no reportable prediction because the model has no decode cost.
Usage: make_scope.py <summary.json> <out.tex>"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from table_style import ratio

# (block title, [(cell, label, F=2 variant, F=1 variant)]): one row per configuration, F=2 and F=1 paired across the columns.
BLOCKS = [("Distinct predicates", [("arxiv_k1600_l3_dist", "arXiv", "P6_lazyscan", "P6_lazyscan_F1"), ("pubmed_k1600_l3_dist", "PubMed", "P6_lazyscan", "P6_lazyscan_F1")]),
          ("Hyperexponential arrivals", [("arxiv_k1600_l3_burst", "arXiv", "P6_lazyscan", "P6_lazyscan_F1"), ("pubmed_k1600_l3_burst", "PubMed", "P6_lazyscan", "P6_lazyscan_F1")]),
          ("Short extraction", [("arxiv_k1600_l3_extract", "arXiv", "P6_lazyscan", "P6_lazyscan_F1")]),
          ("Contiguous ranges, with gain against eager execution alone", [("arxiv_k1600_l3_f1", "arXiv, $b=16$", "P6_lazyscan_b16", "P6_lazyscan_b16_F1"), ("arxiv_k1600_l3_f1", "arXiv, $b=32$", None, "P6_lazyscan_F1"),
                                    ("pubmed_k1600_l3_f1", "PubMed, $b=16$", "P6_lazyscan_b16", "P6_lazyscan_b16_F1"), ("pubmed_k1600_l3_f1", "PubMed, $b=32$", None, "P6_lazyscan_F1")]),
          ("Larger collections", [("arxiv_n5000_k1600_l3", "arXiv, 5,000 documents, 1,600 KV blocks", "P6_lazyscan", "P6_lazyscan_F1"), ("arxiv_n5000_k10000_l3", "arXiv, 5,000 documents, 10,000 KV blocks", "P6_lazyscan", "P6_lazyscan_F1"),
                                  ("pubmed_n3000_k1600_l3", "PubMed, 3,000 documents, 1,600 KV blocks", "P6_lazyscan", "P6_lazyscan_F1"), ("pubmed_n3000_k10000_l3", "PubMed, 3,000 documents, 10,000 KV blocks", "P6_lazyscan", "P6_lazyscan_F1")])]


def side(r, v, other):
    """The five cells of one variant. Within a row, the higher displayed ratio of the F=2, F=1 pair is bold; equal displayed values are not."""
    if v is None:
        return ["\\textendash"] * 5
    g = r["gain"][v]
    o = r["gain"].get(other) if other else None

    def cell(key, seeds):
        win = o is not None and f"{g[key]:.2f}" != f"{o[key]:.2f}" and g[key] > o[key]
        return ratio(g[key], list(g[seeds].values()), bold=win)
    pred = f"{g['pred']:.2f}" if "pred" in g else "\\textendash"
    return [f"{r['policies'][v]['cached']:.2f}", cell("vs_best", "per_seed_vs_best"), pred, cell("vs_adaptive", "per_seed_vs_adaptive"), cell("p95_vs_adaptive", "per_seed_p95_vs_adaptive")]


def main():
    S = json.load(open(sys.argv[1]))
    lines = ["% Generated by figures/make_scope.py; do not edit by hand.", "\\begin{tabular}{@{}lrrrrrrrrrrr}", "\\toprule",
             " & & \\multicolumn{5}{c}{$F=2$} & \\multicolumn{5}{c}{$F=1$} \\\\", "\\cmidrule(lr){3-7}\\cmidrule(l){8-12}",
             "Configuration & Tr. & Cached & Gain & Pred. & Mk & p95 & Cached & Gain & Pred. & Mk & p95 \\\\", "\\midrule"]
    for title, rows in BLOCKS:
        rows = [x for x in rows if x[0] in S]
        if not rows:
            continue
        lines.append(f"\\multicolumn{{12}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\")
        for cell, label, f2, f1 in rows:
            r = S[cell]
            lines.append(f"\\quad {label} & {len(r['seeds'])} & " + " & ".join(side(r, f2, f1) + side(r, f1, f2)) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
